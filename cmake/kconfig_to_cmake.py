import argparse
import os
import sys

try:
    import kconfiglib
except ImportError:
    sys.exit("kconfiglib not found. Install with: pip install kconfiglib")

def main():
    # python kconfig_to_cmake.py --kconfig <Kconfig> --config <.config> --cmake-out <...> --header-out <...>
    parser = argparse.ArgumentParser()
    parser.add_argument("--kconfig",    required=True,  help="Kconfig file")
    parser.add_argument("--config",     default=None,   help=".config file")
    parser.add_argument("--cmake-out",  required=True,  help="output config.cmake")
    parser.add_argument("--header-out", required=True,  help="output autoconf.h")

    args = parser.parse_args()
    kconf = kconfiglib.Kconfig(args.kconfig, warn=False)

    # 如果 .config 存在则加载
    if args.config and os.path.exists(args.config):
        kconf.load_config(args.config)

    # 生成 autoconf.h (默认输出目录已存在)
    kconf.write_autoconf(args.header_out)

    # 生成 config.cmake
    with open(args.cmake_out, "w") as f:
        f.write("# Auto-generated by kconfig_to_cmake.py. Do not edit.\n\n")
        for name, sym in sorted(kconf.syms.items()):
            if not sym.nodes:
                continue
            if sym.type == kconfiglib.UNKNOWN:
                continue

            full = "CONFIG_" + name
            val = sym.str_value

            if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
                # CONFIG_xxx=y  =>  set(CONFIG_xxx TRUE CACHE BOOL "" FORCE)
                # CONFIG_xxx=n  =>  set(CONFIG_xxx FALSE CACHE BOOL "" FORCE)
                f.write(f'set({full} {"TRUE" if val == "y" else "FALSE"} CACHE BOOL "" FORCE)\n')
            elif sym.type == kconfiglib.STRING:
                # CONFIG_xxx="xxx" =>  set(CONFIG_xxx "xxx" CACHE STRING "" FORCE)
                f.write(f'set({full} "{val}" CACHE STRING "" FORCE)\n')
            else:
                f.write(f'set({full} {val} CACHE STRING "" FORCE)\n')

if __name__ == "__main__":
    main()